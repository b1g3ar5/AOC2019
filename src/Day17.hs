crosses :: String -> ([(Int, Int)], String)
crosses s = (cs, intercalate "\n" $ (\r -> (\c -> if (c, r) `elem` cs then 'O' else getP (c,r)) <$> [0..(cols-1)]) <$> [0..(rows - 1)])
  where
    rows = length ls
    cols = length (head ls)
    ls = lines s
    scaffold :: Map (Int, Int) Char
    scaffold = fromList $ concat $ (\(row, l) -> (\(col, c) ->
                                                   ((col, row), c)
                                                 ) <$> zip ([0..]::[Int]) l
                                   ) <$> zip ([0..]::[Int]) ls
    ps = keys scaffold
    cs :: [(Int, Int)]
    cs = filter isCross ps

    getP p = findWithDefault '.' p scaffold
    isCross :: (Int, Int) -> Bool
    isCross p@(x,y) = and $ (=='#') . getP <$> [up , dn, lf, rt, p]
      where
        up = (x, y-1)
        dn = (x, y+1)
        lf = (x-1, y)
        rt = (x+1, y)


insertList :: Ord k => Map k a -> [(k, a)] -> Map k a
insertList m as = go m as
  where
    go m [] = m
    go m ((i, x):ixs) = go (insert i x m) ixs



